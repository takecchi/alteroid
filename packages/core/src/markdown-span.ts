/**
 * **Markdown として書かれていない文字列を、Markdown の文へ埋め込める形にする**（issue #287）。
 *
 * ## これは `markup`（`schema.ts` の `textMarkupSchema`）とは別の機構である
 *
 * `markup` は**1本の文字列全体について「どの記法で書かれているか」を名乗る印**である。
 * だから書き手が複数居て、既に連結されて届いた文字列には立てられない —— 名乗れる値が
 * 無いからで、`schema.ts` の doc が逐語で「**立てられないから立てないのであって、安全
 * だから立てないのではない**」と書いているのはそのことである。**その判断は覆らない。**
 *
 * こちらは印を立てない。**連結する側が、埋め込む直前に、埋め込まれる側を Markdown の
 * 記法として無害な形へ包む。** つまり「混ざったものに札を貼る」のではなく「**混ぜない**」。
 * 名乗る値が要らないので、`markup` が成立しない場所でも成立する。
 *
 * ## 何が化けるかは、実機のレンダラで測った（推定ではない）
 *
 * 測ったのは `apps/web/app/components/markdown.tsx` と**同じ設定**である
 * （`react-markdown` 10.1.0 ＋ `remark-gfm` 4.0.1 ＋ `remark-breaks` 4.0.0、`rehype-raw`
 * 無し）。観測 2026-08-27。
 *
 * **化けた（実測）**:
 *
 * - **バッククォート。** Bash のコマンド置換を含む JSON ダンプ
 *   `{"command":"echo ` + '`date`' + ` && rm -rf /"}` は、`` `date` `` の部分が本物の
 *   `<code>` 要素になった。**これがこの module を書いた理由である**
 * - 空白で挟まれた `_word_`、および空白を挟まない `*word*` は `<em>` になった
 *
 * **化けなかった（実測。ここは前提が1本外れていた）**:
 *
 * - **`mcp__<server>__<tool>` は化けない。** issue #287 のコメントは「`__…__` は強調
 *   記法なので**いま既に化ける**」と書いていたが（形からの推定であることは逐語で
 *   留保されていた）、CommonMark はアンダースコアによる強調を**語中では発火させない**
 *   ので、両側が英数字である MCP のツール名はそのまま残る
 * - glob の `**​/*.ts` を含む JSON ダンプも、有効なデリミタの対が組めず素で残った
 *
 * ⟹ **「Markdown ではない字面を Markdown の文へ素で埋めると化ける」は正しいが、
 * 化けるのは入力次第である。** そして `brief()` が通すのは**ツール呼び出し引数の
 * 任意のダンプ**なので、バッククォートが載る回は来る。入力を選べない以上、
 * 個別の記号を潰して回るのではなく、**欄ごと包む**のが形として正しい。
 *
 * ## 包まないもの（意図的な線）
 *
 * **SDK が書いた prose（拒否理由・上限の文言など）はここでは包まない。** 包めないから
 * ではなく、**包むと等幅になって「文章」ではなく「コード」として描かれる**からで、それは
 * SDK の prose をどの面でどう描くかという**表示の方針**の話になる（`reports.tsx` と
 * issue #285 が面ごとに別の判断を書いている）。ここはその方針を決める場所ではない。
 * ⟹ **条件（方針が決まる）が変われば覆る種類の見送りである。** 上の `markup` の
 * 「立てられない」とは別の理由でやっていない、ということを混ぜないために書いておく。
 */

/**
 * `text` を Markdown のインラインコードとして包む。**中身は字面のまま残る。**
 *
 * 包みの長さを中身に合わせて決める（可変長フェンス）。バッククォートを含む文字列を
 * 1本のバッククォートで包むと、そこで閉じてしまって以降の本文まで巻き込む —— JSON
 * ダンプには実際にバッククォートが載る（上の実測）ので、これは起こりうる話ではなく
 * 起こる話である。
 *
 * **空文字は包まない。** 包むと「空のコード」という**無い事実**を描くことになる
 * （AGENTS.md の地雷「取れない軸に 0 の行を作る」と同じ形）。呼び出し側で欄ごと
 * 省くかどうかを決められるよう、空文字をそのまま返す。
 *
 * **既知の限界: 改行を含む文字列は扱わない。** Markdown のインラインコードは改行を
 * 空白へ潰すので、包んでも字面は保たれない。いまの呼び出し元（SDK のツール名、
 * `JSON.stringify` の出力）はどちらも生の改行を含まないので、ここでは検出も置換も
 * しない —— **黙って直す代わりに、直せないことを書いておく**。
 */
export function codeSpan(text: string): string {
  if (text === '') return '';

  // 中身にあるバッククォートの**最長の連なり**より1本長い包みを使う。
  const runs = text.match(/`+/g);
  const longest = runs === null ? 0 : Math.max(...runs.map((run) => run.length));
  const fence = '`'.repeat(longest + 1);

  // **端が空白かバッククォートなら、内側へ空白を1つずつ足す。** CommonMark は
  // 「両端が空白で、かつ全部が空白ではない」ときに限って前後から空白を1つずつ
  // 取り除く。だから両端に足せば、取り除かれた後に元の字面が戻る。
  //
  // - 端がバッククォートのとき: 足さないと包みと中身が繋がって、フェンスの長さが
  //   変わってしまう
  // - 端が空白のとき: 足さないと**中身の空白のほうが**取り除かれて字面が変わる
  const padded = /^[ `]/.test(text) || /[ `]$/.test(text);
  const pad = padded ? ' ' : '';

  return `${fence}${pad}${text}${pad}${fence}`;
}
