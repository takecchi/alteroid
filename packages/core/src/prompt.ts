/**
 * 蒸留の指示。会話終了時・PreCompact 時・定期の棚卸しで、枕の理由だけを変えて同じ本体を投げる
 * （会話終了と棚卸しは本セッションの内部ターン、PreCompact は生ログの末尾を添えた別の短命セッション）。
 *
 * 統合（重複の掃除・要旨と区分の整備）の指示もここに乗せる: 区分が無い文書は `premise` が既定なので、
 * 蒸留が要旨と区分を書いて重複を畳まない限り、毎ターンの焼き込みは軽くならない。
 */
export interface DistillPromptOptions {
  /**
   * いま毎ターンの焼き込みに収まっていない文書の一覧（`describeMemoryTidyTargets` の出力そのまま）。
   * 定期の棚卸し（`reason: 'scheduled'`）だけが渡す: 会話終了・PreCompact は会話を記憶へ移すのが
   * 本題で、的の一覧を足すと薄まる。文字列で受け取る: 文書から組み立てると指示文が記憶の構造を知ることになる。
   */
  tidyTargets?: string;
  /**
   * 固定の本体（理由によらず同じ2つの塊）を通す関数。`DigestSessionDelta.fixed` を渡すと、同じ会話の2回目以降は
   * `ref`（短い参照）になる。省略すると常に全文。pre_compact は別の短命セッションなので渡さない。
   */
  fold?: (id: string, full: string, ref: string) => string;
}

export function buildDistillPrompt(
  reason: 'conversation_end' | 'pre_compact' | 'scheduled',
  options: DistillPromptOptions = {},
): string {
  const why =
    reason === 'pre_compact'
      ? 'この会話の文脈はまもなく要約に潰され、細部は失われる。'
      : reason === 'scheduled'
        ? '定期の棚卸しの刻みが来た。**会話が終わったからではない**——記憶は育ち続けるので、' +
          '溜まったものを畳むために定期的に起こしている。'
        : 'いまの会話が終わった。この文脈はやがて失われる。';
  const tidySection =
    options.tidyTargets === undefined
      ? ''
      : `
## 棚卸しの的（いま測った値。この刻みでいちばん効く仕事はここに在る）

${options.tidyTargets}

**上に名前が出ている文書から手を付けよ。** 出ていなければ、下の「統合」を通常どおり行えばよい。
`;
  // 固定の本体（理由ごとに変わらない部分）だけを `fold` に通す。枕（`why`）と棚卸しの的は毎回そのまま出す
  const fold = options.fold ?? ((_id: string, full: string) => full);
  return (
    `[system] ${why}\n\n` +
    fold('distill-instructions-intro', DISTILL_INTRO, DISTILL_INTRO_REF) +
    `\n\n${tidySection}\n` +
    fold('distill-instructions-consolidation', DISTILL_CONSOLIDATION, DISTILL_CONSOLIDATION_REF)
  );
}

