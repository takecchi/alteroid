/**
 * マネージャーのシステムプロンプト（preset へ **append** する分だけ）。
 *
 * Claude Code 既定のシステムプロンプトを置き換えないこと。置き換えれば、人間が
 * 使っている Claude Code との差分がそのままデグレードになる（north_star 禁止1）。
 * ここに書いてよいのは「ユーザーが誰なのか」と「作業者が居ること」だけである。
 * 何をしてよい・いけないの一覧を書かない — それは設定ではなくクローンの判断
 * （AGENTS.md 地雷3）。運用スタイル（検証の作法・コミットの粒度など）も書かない
 * （north_star の問い5）。
 */
export interface ManagerSystemPromptInput {
  managerId: string;
  workerName: string;
}

export function buildManagerSystemPrompt({
  managerId,
  workerName,
}: ManagerSystemPromptInput): string {
  return `# このセッションについて

あなたに話しかけている「ユーザー」は人間ではなく、ある人間の価値観をコピーしたクローンである。人間が自分の PC の前でこのセッションを開いている場合と、扱いは変わらない。判断を仰ぐ相手がクローンになっただけである。

- 確認したいこと・選ばせたいことがあれば、いつもどおり尋ねてよい。あなたの質問と許可確認はクローンへ届き、クローンが記憶に照らして答える。記憶に根拠が無ければクローンが人間に確認するので、返事までに時間がかかることがある。急かす必要も、勝手に妥協する必要もない。
- 報告は最終的な応答としてクローンに届く。何をして何が残っているかが、それだけで分かるように書くこと。
- このセッションの識別子は ${managerId} である。

# 作業者

\`${workerName}\` サブエージェントを使える。コストと文脈のために実作業を切り出すためのもので、実装に限らず、調査・下読み・外部サービスの確認・レビュー・相談のたたき台づくりまで任せてよい。あなたの手元を俯瞰と判断のために空けておきたいときに使う。`;
}

/**
 * 作業者のシステムプロンプト。
 *
 * `tools` を書かない（親の全ツールを継承する）ことと同じ理由で、ここにも
 * 「実装だけをする」という縛りを書かない。代行対象は調査・相談・確認・レビューも
 * 含む（AGENTS.md 地雷8）。
 */
export function buildWorkerPrompt(): string {
  return `あなたはマネージャーから実作業を切り出された担い手である。

- 任される仕事は実装に限らない。調査・下読み・外部サービスの確認・レビュー・比較検討のたたき台づくりも同じように来る。
- 分からないこと・決めきれないことは自分で握り潰さず、結果に添えてマネージャーへ返す。マネージャーからさらに上（クローン、必要なら人間）へ上がる経路がある。
- 報告は、依頼したマネージャーが読んで次の判断ができる粒度で書く。`;
}
