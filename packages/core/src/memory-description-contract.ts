// 記憶の要旨（frontmatter の `description`）の書き方の約束。道具の説明・システムプロンプト・統合（distill）の指示が同じ文を使う。
//
// 要旨はクローンが本文を開く前に読める唯一の場所である（premise はカード、indexed は要旨だけ、fact は目次の1行）。
// 本文を開くかどうかの判断も、開かなくても守る約束事の読みも、ここだけで決まる。だから、要旨に何を書くかを約束として持つ。
// 一覧へ本文を載せない設計（`.claude/skills/listing-and-detail/SKILL.md`）の裏面である:
// 本文を載せない代わりに、載せるものへ「開く条件」と「漏れてはいけない約束事」を必ず載せる。
//
// 要旨の中身（約束事・開く条件を書いたか）は機械では検査しない: 言い回しで見ると誤検知が多く、通すための書き方へ寄せる誘因になるため。
// 長さのほうは既存の「要旨が長すぎる」印と、fact の目次の行の「…（N 文字省略）」が受け持つ。

/** 要旨に書く2つ。区分（premise・indexed・fact）を問わず同じ。 */
export const MEMORY_DESCRIPTION_CONTRACT_CORE =
  '**要旨（description）には次の2つを必ず書く。約束事を先頭に置く。** ' +
  '(1) **本文を開かなくても守るべき約束事**（絶対に漏れてはいけない規則・禁止・前提。本文の奥にだけ書いて要旨から落とさない。無ければ書かない）。' +
  '(2) **本文をいつ開くべきか**（開く条件。「〜のときは開く」の形）。' +
  '本文の中身そのものは書かない（書くのは約束事と開く条件だけ。短く保つ）。';

/**
 * fact は目次の1行へ要旨の先頭 `factLineLimit` 字しか載らない（それ以降は「…（N 文字省略）」になる）。
 * 約束事を先頭に置く理由はここにある: 切られるのは末尾で、約束事が末尾にあると毎ターンの判断から消える。
 */
export function memoryDescriptionContract(factLineLimit: number): string {
  return (
    `${MEMORY_DESCRIPTION_CONTRACT_CORE} ` +
    `**fact は要旨の先頭 ${String(factLineLimit)} 字しか目次に載らない**ので、約束事と開く条件を先頭の ${String(factLineLimit)} 字に収める` +
    '（収まらない約束事があるなら、その文書は fact ではなく indexed か premise にする）。'
  );
}
