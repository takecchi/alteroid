// 会話の一覧の1行（サーバの `preview`: 改行を空白に畳み、80字で切った Markdown）から、記号を落とした素の文を作る。
// 完全な Markdown の解釈はしない: 切り口でリンクや強調が閉じていないことがあり、改行も畳まれていて行頭が分からないため、
// 「空白で区切られた記号」と「対で閉じた記号」だけを落とす（a*b や snake_case のような普通の文は触らない）。
export function plainPreview(markdown: string): string {
  return (
    markdown
      // 画像・リンクは文字だけ残す。80字で切られて `)` が無いものも同じ
      .replace(/!?\[([^\]]*)\]\([^)]*\)?/g, '$1')
      .replace(/```/g, ' ')
      .replace(/`([^`]*)`/g, '$1')
      .replace(/(\*\*|__)(?=\S)(.+?)(?<=\S)\1/g, '$2')
      .replace(/~~(?=\S)(.+?)(?<=\S)~~/g, '$1')
      .replace(/(?<![\w*])\*(?=[^\s*])(.+?)(?<=[^\s*])\*(?![\w*])/g, '$1')
      .replace(/(?<![\w_])_(?=[^\s_])(.+?)(?<=[^\s_])_(?![\w_])/g, '$1')
      // 見出し・箇条・引用の記号。行頭は畳まれて空白になっているので、空白で区切られた記号だけを見る
      .replace(/(^|\s)#{1,6}\s+/g, '$1')
      // 文中の `-` は箇条の記号として落とす（`2 - 3` のような数の前は引き算なので残す）。`*` `+` は文中では掛け算・足し算と区別できないので、先頭だけ
      .replace(/(^|\s)-\s+(?=[^\d\s])/g, '$1')
      .replace(/^[*+]\s+/, '')
      .replace(/^\d{1,3}[.)]\s+/, '')
      .replace(/^>\s?/, '')
      .replace(/\s+/g, ' ')
      .trim()
  );
}
