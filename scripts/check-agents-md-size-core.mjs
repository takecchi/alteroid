/**
 * `check-agents-md-size.mjs` の判定だけを切り出したもの
 * （`check-web-bundle-size-core.mjs` と同じ分け方）。
 *
 * **切り出したのはテストのためである。** ファイル IO を CLI 側に残し、ここには
 * 判定ロジックだけを置く。ここでは合成した `{ bytes, lines }` で判定だけを試せる。
 * **ファイル読み込みはしない**（読むのは CLI 側）。
 *
 * ## なぜこの歯が要るか（#1192）
 *
 * Issue #1192 の指摘: `AGENTS.md` は「注意書きを増やす速度」と「機械で確かめられる
 * 条件を歯（テスト・型）へ移す速度」が釣り合っていない。前者だけが進むと、この
 * 文書はいつまでも太り続ける。**この歯そのものが「歯へ移す」側の実践である** —
 * 「大きくなりすぎたら気づけ」という注意書きを、機械の判定に置き換える。
 *
 * **畳んでもすぐ増える実例が実際にある。** `f2adf86`（5ブロックを
 * `.claude/skills/` へ移して縮めた）の**同日、15分後**の `40dfab4` で
 * +638 バイト増えている（2026-09-17 実測。畳んだ**翌日**ではなく**同日**——
 * 依頼時点の見立てはここが違っていたので、実測に合わせて訂正した）。
 * しかもこの +638 バイトは無駄な追記ではなく、直前の記述の**誤りの訂正**
 * （「cat の打ち切り閾値は文字ではなくバイトである」）だった。**⟹ 縮めても
 * 増える力は止まらない。しかも増分の質を見ても「悪い増分」とは言えない**
 * ——正しい訂正でも文書は太る。だから「内容の質で止める」は機能しない
 * （下の「この歯の弱さ」も参照）。
 *
 * ## ⭐ バイト数は代理変数にすぎない
 *
 * **本当に測りたいのは「新しい作業のたびに、この文書から重要な判断基準を
 * 取り出す負担」であって、バイト数そのものではない。** 読む負担は、内容の
 * 構成・重複の有無・すでに知っている文脈の量など、バイト数だけでは決まらない
 * 要因に左右される。**バイト数は、その負担が測れないので代わりに置いた代理
 * 変数でしかない。** 代理変数である以上、バイト数を予算内に収めても「読む
 * 負担が減った」とは言えない（`.claude/skills/` へ移せば身軽になるが、それは
 * 「読む主体がどこを引くか」という別の変数であって、この歯が測る値ではない
 * — 下の「この歯の弱さ」）。
 *
 * ## なぜ余白ゼロか
 *
 * `check-web-bundle-size.mjs` の予算は実測の約1.4倍の余白を持つ——理由は
 * **ビルド生成物のバイト数が、依存やバンドラの版だけでも測定のたびに揺らぐ**
 * ためで、余白が無いと無関係な揺らぎで偽陽性が出る。
 *
 * **この歯にはその理由が無い。** `AGENTS.md` のバイト数は、人間または AI が
 * この文書を編集したときにしか動かない——**測定のゆらぎを一切持たない**。
 * 偽陽性が原理的に起きないので、余白を持つ理由も無い。**余白を持たせると、
 * その余白のぶんは無審査で増やせることになる**——ラチェットの意味が薄れる。
 * だから `BUDGET_HISTORY` の最新の実測値をそのまま予算に据え、余白はゼロにする。
 *
 * ## 逃げ道の設計 — なぜ `BUDGET_HISTORY` への理由付き追記にしたか
 *
 * 正当な追記（要件が増えた・重大な地雷が見つかった等）まで止めてはならない
 * ので、予算を上げる逃げ道は要る。**その逃げ道を「`BUDGET_HISTORY` に1件足し、
 * `why` に理由を書く」という形にしたのは、数字だけを上げることをできなく
 * するためである。** 予算 (`AGENTS_MD_MAX_BYTES`) は履歴の最新の件から**導出**
 * するので、履歴を足さずに数字だけを書き換える経路が無い。
 *
 * ⚠️ **この歯が測れるのは `why` が非空であることだけである。** `why` の中身が
 * 正しいか・その理由が妥当かは、この歯には判定できない——`check-scripts-wired.
 * test.ts` の `EXEMPT` の doc が持つのと同じ断りがここにも要る:
 * 「後で配線する」を書いて放置されても、機械には捕まらない。**内容の正しさは
 * 人のレビューが見る。**
 *
 * ## この歯の弱さ
 *
 * - **バイト数しか見ない。読む負担そのもの（判断基準を取り出す手数）は
 *   測っていない。** 上の「バイト数は代理変数にすぎない」がその理由である
 * - **`Read` ツールのトークン上限は測っていない。** #1192 自身も「53,145
 *   トークンという値は測り直していない」と断っている。この歯もバイト数と
 *   トークン数の対応関係を一切確かめていない
 * - **一方向のラチェットである。縮んでも予算は自動で下がらない。** ⟹ 一度
 *   増えた予算はそのまま残り、次の追記はその余白ぶんは無審査で通る。予算を
 *   下げるのは人の仕事——だから通ったとき（緑のとき）も必ず余白（`slackBytes`）
 *   を出力する。出しておかないと、下げる判断の機会そのものが見えなくなる
 * - **移し先（`.claude/skills/`）を見ていない。** `.claude/skills/` へ内容を
 *   移せばこの歯は緑になるが、読む側の負担が本当に減ったかはこの歯には
 *   分からない。実測（2026-09-17）: `.claude/skills/` 配下の合計バイト数は
 *   `AGENTS.md` より大きい。CLI はこの値を**参考として**出す（判定には使わない
 *   ——`.claude/` は別の担当の領域であり、この歯で赤くしない）
 * - **内容の質を見ない。** 正しい訂正の +638 バイトと、無駄な追記の +638
 *   バイトを、この歯は区別しない。上の「畳んでもすぐ増える実例」がまさに
 *   その例（訂正であって無駄ではないのに、同じだけバイト数を押し上げた）
 */

