/** 現在の予算（バイト）。`BUDGET_HISTORY` の最新の件から導出する。 */
export const AGENTS_MD_MAX_BYTES = BUDGET_HISTORY[BUDGET_HISTORY.length - 1].bytes;

/** `cat` が一度に返す上限（バイト）。`AGENTS.md`「踏みやすい地雷」の実測。 */
export const CAT_WINDOW_BYTES = 30_000;

/**
 * `{ bytes, lines }` を予算と突き合わせて判定する。ファイル IO はしない。
 *
 * 返す形:
 * - `ok`: `bytes` が予算を超えていないか（一方向のラチェット。超えたときだけ NG）
 * - `bytes` / `lines`: 渡されたそのままの値
 * - `budget`: 予算（バイト）
 * - `overBytes`: 予算からの超過分（バイト）。超えていなければ 0
 * - `overPercent`: 予算に対する超過率（%）。超えていなければ 0
 * - `usedPercent`: 予算に対する使用率（%）。縮んでいても 100 を下回るだけで
 *   マイナスにはならない
 * - `slackBytes`: 予算 − 実測（余白）。超過していれば 0（マイナスにしない —
 *   超過分は `overBytes` の役目）
 * - `catWindows`: `cat` の打ち切り（`CAT_WINDOW_BYTES`）で何回に分かれるか
 *   （`Math.ceil(bytes / CAT_WINDOW_BYTES)`）
 */
export function judgeAgentsMdSize({ bytes, lines }) {
  const budget = AGENTS_MD_MAX_BYTES;
  const over = bytes > budget;
  const overBytes = over ? bytes - budget : 0;
  const overPercent = over ? (overBytes / budget) * 100 : 0;
  const slackBytes = over ? 0 : budget - bytes;

  return {
    ok: !over,
    bytes,
    lines,
    budget,
    overBytes,
    overPercent,
    usedPercent: (bytes / budget) * 100,
    slackBytes,
    catWindows: Math.ceil(bytes / CAT_WINDOW_BYTES),
  };
}
