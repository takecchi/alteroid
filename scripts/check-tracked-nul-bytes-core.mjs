/** NUL（コードポイント0）を指す1文字。エスケープ表記ではなく `String.fromCharCode`
 * で作る——理由はこのファイル冒頭の「この検査を書く最中に…」節。 */
export const NUL_CHAR = String.fromCharCode(0);

/**
 * `files`（`{ path, content }` の配列）を走査し、NUL バイトを含むものを返す。
 * `content` は文字列（`readFileSync(path, 'utf8')` 等）を想定する——NUL
 * （コードポイント0）は UTF-8 の1バイト文字としてそのまま往復するので、
 * 他のバイトが多バイト文字として壊れていても NUL の検出そのものは影響を受けない。
 *
 * 1ファイルにつき最初の1件だけを返す（`findNodeTraceHits` / `findInvalidCssHits`
 * と同じ割り切り——「混入したかどうか」だけを見る検査なので、件数の精度は求めない）。
 */
export function findNulByteHits(files) {
  const hits = [];
  for (const file of files) {
    const index = file.content.indexOf(NUL_CHAR);
    if (index !== -1) {
      hits.push({
        path: file.path,
        index,
        snippet: file.content.slice(Math.max(0, index - 20), index + 20),
      });
    }
  }
  return hits;
}
